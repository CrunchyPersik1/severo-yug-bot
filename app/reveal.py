"""Прокрут приза в стиле CS2: быстро уехало — плавно доехало.

Никаких стадий, проскоков и дополнительных сдвигов: одна непрерывная
анимация с длинным «хвостом» замедления. Лента летит на старте и плавно
тормозит к финишу, поэтому последние доли секунды видно, куда именно она
встаёт — без рывков и без съезда на соседнюю награду.
"""

from __future__ import annotations

# Длительность прокрута: лента кейса и лента рулетки.
REEL_MS = 4500

# Колесо чуть дольше: ему нужно докрутиться до сегмента.
WHEEL_MS = 5000

# Пауза перед показом текста результата: даём ленте «щёлкнуть».
HOLD_MS = 350

# Кривая: резкий старт, длинный тормозной хвост (как в кейсах CS).
CURVE = "cubic-bezier(.08,.78,.1,1)"


def reel_ms() -> int:
    return REEL_MS


def wheel_ms() -> int:
    return WHEEL_MS


def payload() -> dict[str, object]:
    """Параметры анимации для страниц."""
    return {
        "reel_ms": REEL_MS,
        "wheel_ms": WHEEL_MS,
        "hold_ms": HOLD_MS,
        "curve": CURVE,
    }
